create table app_user (
 id bigint generated by default as identity primary key, first_name varchar(80) not null,
 last_name varchar(80) not null, email varchar(254) not null unique, document varchar(40),
 password_hash varchar(100) not null, role varchar(20) not null check(role in ('TOURIST','PROVIDER','ADMIN')),
 active boolean not null default true, created_at timestamp with time zone not null default current_timestamp);
create table department(id bigint primary key,name varchar(100) not null unique);
create table locality(id bigint primary key,department_id bigint not null references department(id),name varchar(100) not null,unique(id,department_id));
create table venture(
 id bigint generated by default as identity primary key, owner_id bigint not null unique references app_user(id),
 legal_type varchar(20) not null check(legal_type in ('PHYSICAL','LEGAL')), commercial_name varchar(150) not null,
 legal_name varchar(200),tax_id varchar(40),contact_email varchar(254) not null,phone varchar(40) not null,
 department_id bigint not null references department(id),locality_id bigint not null,
 location_description varchar(300) not null,description varchar(5000) not null,
 verification_status varchar(20) not null default 'PENDING' check(verification_status in ('PENDING','VERIFIED')),
 verified_by bigint references app_user(id),verified_at timestamp with time zone,
 foreign key(locality_id,department_id) references locality(id,department_id));
create table category(id bigint generated by default as identity primary key,name varchar(150) not null,normalized_name varchar(150) not null unique,active boolean not null default true);
create table equipment_type(id bigint generated by default as identity primary key,name varchar(150) not null,normalized_name varchar(150) not null unique,active boolean not null default true);
create table activity(
 id bigint generated by default as identity primary key,venture_id bigint not null references venture(id),name varchar(150) not null,
 description varchar(5000) not null,unit_price numeric(12,2) not null check(unit_price>0),currency varchar(3) not null default 'UYU',
 duration_minutes integer not null check(duration_minutes>0),booking_lead_minutes integer not null check(booking_lead_minutes>=0),
 department_id bigint not null references department(id),locality_id bigint not null,
 location_description varchar(300) not null,min_age integer check(min_age between 0 and 120),conditions varchar(5000) not null,
 is_published boolean not null default false,
 foreign key(locality_id,department_id) references locality(id,department_id));
create table activity_category(activity_id bigint not null references activity(id),category_id bigint not null references category(id),primary key(activity_id,category_id));
create table activity_equipment(activity_id bigint not null references activity(id),equipment_id bigint not null references equipment_type(id),mode varchar(10) not null check(mode in ('PROVIDED','REQUIRED')),primary key(activity_id,equipment_id));
create table activity_instance(
 id bigint generated by default as identity primary key,activity_id bigint not null references activity(id),
 starts_at timestamp with time zone not null,ends_at timestamp with time zone not null,capacity integer check(capacity>0),active boolean not null default true,
 check(ends_at>starts_at),unique(activity_id,starts_at));
create table reservation(
 id uuid primary key,tourist_id bigint not null references app_user(id),instance_id bigint not null references activity_instance(id),
 idempotency_key varchar(100) not null,participant_count integer not null check(participant_count>0),
 status varchar(30) not null check(status in ('PENDING_PAYMENT','PAYMENT_UNCERTAIN','CONFIRMED','COMPLETED','REJECTED','EXPIRED','PAYMENT_CANCELLED')),
 expires_at timestamp with time zone not null,activity_name_snapshot varchar(150) not null,location_snapshot varchar(300) not null,
 unit_price_snapshot numeric(12,2) not null,currency varchar(3) not null,total_amount numeric(16,2) not null,
 starts_at_snapshot timestamp with time zone not null,ends_at_snapshot timestamp with time zone not null,
 lead_minutes_snapshot integer not null,code varchar(50) unique,created_at timestamp with time zone not null,
 unique(tourist_id,idempotency_key));
create table payment(
 id uuid primary key,reservation_id uuid not null unique references reservation(id),merchant_reference varchar(100) not null unique,
 external_payment_id varchar(100) unique,status varchar(20) not null,amount numeric(16,2) not null,currency varchar(3) not null,
 checkout_url varchar(1000),approved_at timestamp with time zone,last_checked_at timestamp with time zone);
create table payment_event(event_id varchar(100) primary key,payment_id varchar(100) not null,received_at timestamp with time zone not null,processed_at timestamp with time zone);
create table review(
 id bigint generated by default as identity primary key,reservation_id uuid not null unique references reservation(id),
 rating integer not null check(rating between 1 and 5),comment varchar(2000),created_at timestamp with time zone not null);
create index instance_activity_time on activity_instance(activity_id,starts_at);
create index reservation_instance_status on reservation(instance_id,status);
create index reservation_tourist_time on reservation(tourist_id,created_at);
create index activity_venture on activity(venture_id);
create index review_created on review(created_at,reservation_id);
create index venture_verification on venture(verification_status);
